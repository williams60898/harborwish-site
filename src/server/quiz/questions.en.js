/**
 * 取某一维的「16 道题池子」。rotation 可把某道底盘题切到它的潮版。
 * @param {string} dimKey 'valence' | 'energy' | ...
 * @param {object} rotation 形如 { 'valence-2': 'trend-1' }：底盘题 id → 潮题 id。
 *        每替换一道，池子仍是 16 道（孪生二选一），绝不撞题。
 */
export function buildPool(dimKey, rotation = {}) {
  const dim = BANK[dimKey];
  if (!dim) throw new Error(`没有这个维度：${dimKey}`);
  return dim.base.map((base) => {
    const trendId = rotation[base.id];
    if (trendId) {
      const t = TRENDS.find((x) => x.id === trendId && x.twin === base.id);
      if (t) return { ...t.q, replacesBase: base.id }; // 用潮版顶替，分数仍按位置
    }
    return base;
  });
}

/**
 * 从池子里随机抽 3 道。优先抽 exclude 里没有的（用于跨次重测不撞题）。
 * @param {Array} pool buildPool 的结果
 * @param {string[]} exclude 已出过的题 id
 */
export function drawThree(pool, exclude = []) {
  const ex = new Set(exclude);
  const fresh = pool.filter((item) => !ex.has(item.id));
  const used = pool.filter((item) => ex.has(item.id));
  const shuffle = (arr) => arr.map((v) => [Math.random(), v]).sort((a, b) => a[0] - b[0]).map((p) => p[1]);
  return shuffle(fresh).concat(shuffle(used)).slice(0, 3); // 先尽量用新题，不够再回收
}

export default { BANK, TRENDS, buildPool, drawThree };
